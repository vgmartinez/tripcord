// Package benign builds and checks the benign-corpus repository index.
// The index names third-party repositories. It does not contain their files.
package benign

import (
	"bytes"
	"fmt"
	"regexp"
	"slices"
	"strings"
	"time"
)

// Harnesses are the root agent configs the index records, in the order
// used for stratification and for the comma list.
var Harnesses = []string{
	"agents",
	"claude",
	"codex",
	"copilot",
	"cursor",
	"devcontainer",
	"gemini",
	"mcp",
	"vscode",
}

// Size bands use the repository size reported by the API, in kibibytes.
// Small is under 1 MB, medium is under 10 MB, and large is the rest.
const (
	SizeSmallMaxKB  = 1024
	SizeMediumMaxKB = 10 * 1024
)

// Verdicts records the triage decisions.
const (
	VerdictTP       = "TP"
	VerdictFP       = "FP"
	VerdictAccepted = "accepted-risk"
)

var (
	shaRE         = regexp.MustCompile(`^[0-9a-f]{40}$`)
	dateRE        = regexp.MustCompile(`^[0-9]{4}-[0-9]{2}-[0-9]{2}$`)
	repoRE        = regexp.MustCompile(`^[A-Za-z0-9-]{1,39}/[A-Za-z0-9._-]{1,64}$`)
	ruleRE        = regexp.MustCompile(`^TC-[A-Z]+-\d{3}$`)
	fingerprintRE = regexp.MustCompile(`^tcf_[0-9a-f]{16}$`)
)

// legacyLockHeader is the comment prefix of a five-column lock from
// before the size-band column. LoadLock still reads it. A new file
// uses Header.
const legacyLockHeader = `# corpus/benign/repos.lock
# Generated by scripts/benign-repos from the GitHub code search API
# (a read-only GITHUB_TOKEN). It searches for a root agent config:
# .claude/settings.json, .mcp.json, .cursor/, AGENTS.md,
# .vscode/tasks.json, .github/workflows/copilot-setup-steps.yml,
# .devcontainer/, .codex/, and .gemini/.
# A repository is kept when it has at least 50 stars and is not
# archived and not a fork. The list is stratified by harness and by
# repository size (small is under 1 MB, medium is under 10 MB, and
# large is the rest) and targets 1000 repositories.
# This copy is partial: 132 of 1,000 repositories. mcp, copilot,
# devcontainer, codex, and gemini have no rows yet. A resumable crawl
# fills the list in. v0 doesn't ship until it reaches at least 1,000
# repositories with a minimum per harness (#41).
# Columns, tab-separated: owner/repo, 40-character commit SHA of the
# default branch HEAD at generation time, SPDX license (NOASSERTION
# when the API reports none), harnesses (comma-separated), date
# (YYYY-MM-DD).
# Generated 2026-11-04.
# This file changes only through a pull request.
`

// TriageHeader is the only comment prefix triage.tsv may have.
const TriageHeader = `# corpus/benign/triage.tsv
# Triage decisions for findings on the benign corpus. There are no rows yet.
# This file changes only through a pull request.
# Columns, tab-separated:
# fingerprint: the finding fingerprint (tcf_ and 16 lowercase hex digits). Unique per repository.
# rule id: a TC rule id that is listed in rules/REGISTRY, such as TC-CFG-001.
# repo: owner/repo. Every value must appear in repos.lock.
# verdict: TP, FP, or accepted-risk.
# reason: why that verdict was chosen. 16 to 200 bytes of printable ASCII, with no URL, host, IP address, or high-entropy token.
# date: YYYY-MM-DD.
`

// Repo is one row of repos.lock. Stars and SizeKB are used to stratify
// the list and are not written to the file.
type Repo struct {
	Name      string
	SHA       string
	License   string
	Harnesses []string
	Date      string
	Band      string
	Stars     int
	SizeKB    int
}

// Triage is one row of triage.tsv.
type Triage struct {
	Fingerprint string
	RuleID      string
	Repo        string
	Verdict     string
	Reason      string
	Date        string
}

// FormatLock renders repos as repos.lock. The rows are sorted by
// owner/repo. The header is Header, so its counts match the rows.
func FormatLock(repos []Repo, when time.Time) ([]byte, error) {
	sorted := slices.Clone(repos)
	for i := range sorted {
		if sorted[i].Band == "" {
			sorted[i].Band = SizeBand(sorted[i].SizeKB)
		}
	}
	slices.SortFunc(sorted, func(a, b Repo) int {
		return strings.Compare(a.Name, b.Name)
	})
	var b bytes.Buffer
	b.WriteString(Header(sorted, when))
	for _, r := range sorted {
		line, err := formatRepo(r)
		if err != nil {
			return nil, err
		}
		b.WriteString(line)
		b.WriteByte('\n')
	}
	return b.Bytes(), nil
}

func formatRepo(r Repo) (string, error) {
	h, err := joinHarnesses(r.Harnesses)
	if err != nil {
		return "", fmt.Errorf("%s: %w", r.Name, err)
	}
	license := r.License
	if license == "" {
		license = "NOASSERTION"
	}
	if !knownLicense(license) {
		return "", fmt.Errorf("%s: unknown license %q", r.Name, license)
	}
	band := r.Band
	if band == "" {
		band = SizeBand(r.SizeKB)
	}
	row := Repo{Name: r.Name, SHA: strings.ToLower(r.SHA), License: license, Harnesses: splitHarnesses(h), Band: band, Date: r.Date}
	if err := checkRepo(row); err != nil {
		return "", err
	}
	return strings.Join([]string{row.Name, row.SHA, row.License, h, row.Band, row.Date}, "\t"), nil
}

// ParseLock reads a repos.lock whose header is Header for its rows.
// Any other comment, a blank line, a carriage return, or a line over
// maxLineBytes is rejected.
func ParseLock(data []byte) ([]Repo, error) {
	head, body, err := splitLock(data, lockHeaderLines())
	if err != nil {
		return nil, err
	}
	repos, err := parseLockRows(body, lockHeaderLines(), true)
	if err != nil {
		return nil, err
	}
	when, err := headerDate(head)
	if err != nil {
		return nil, err
	}
	if string(head) != Header(repos, when) {
		return nil, fmt.Errorf("repos.lock: header is not the generated header")
	}
	return repos, nil
}

// LoadLock reads either the current lock or a five-column lock written
// before the size-band column.
func LoadLock(data []byte) ([]Repo, error) {
	if len(data) == 0 {
		return nil, nil
	}
	if bytes.HasPrefix(data, []byte(legacyLockHeader)) {
		return parseLegacy(data)
	}
	return ParseLock(data)
}

func parseLegacy(data []byte) ([]Repo, error) {
	n := strings.Count(legacyLockHeader, "\n")
	_, body, err := splitLock(data, n)
	if err != nil {
		return nil, err
	}
	if !bytes.HasPrefix(data, []byte(legacyLockHeader)) {
		return nil, fmt.Errorf("repos.lock: header is not the generated header")
	}
	return parseLockRows(body, n, false)
}

func splitLock(data []byte, headerLines int) (head string, body []string, err error) {
	for i, line := range strings.Split(string(data), "\n") {
		if len(line) > maxLineBytes {
			return "", nil, fmt.Errorf("repos.lock:%d: line is %d bytes, limit %d", i+1, len(line), maxLineBytes)
		}
	}
	if bytes.Contains(data, []byte{'\r'}) {
		return "", nil, fmt.Errorf("repos.lock: carriage return")
	}
	lines := strings.Split(string(data), "\n")
	if len(lines) > 0 && lines[len(lines)-1] == "" {
		lines = lines[:len(lines)-1]
	}
	if len(lines) < headerLines {
		return "", nil, fmt.Errorf("repos.lock: header is not the generated header")
	}
	for i, line := range lines[headerLines:] {
		if line == "" || strings.HasPrefix(line, "#") {
			return "", nil, fmt.Errorf("repos.lock:%d: comment or blank line outside the header", headerLines+i+1)
		}
	}
	return strings.Join(lines[:headerLines], "\n") + "\n", lines[headerLines:], nil
}

func parseLockRows(lines []string, headerLines int, withBand bool) ([]Repo, error) {
	want := 5
	if withBand {
		want = 6
	}
	var out []Repo
	for i, line := range lines {
		fields := strings.Split(line, "\t")
		if len(fields) != want {
			return nil, fmt.Errorf("repos.lock:%d: %d columns, want %d", headerLines+i+1, len(fields), want)
		}
		r := Repo{
			Name:      fields[0],
			SHA:       fields[1],
			License:   fields[2],
			Harnesses: splitHarnesses(fields[3]),
		}
		if withBand {
			r.Band = fields[4]
			r.Date = fields[5]
		} else {
			r.Date = fields[4]
		}
		if err := checkRepo(r); err != nil {
			return nil, fmt.Errorf("repos.lock:%d: %w", headerLines+i+1, err)
		}
		if withBand && r.Band == "" {
			return nil, fmt.Errorf("repos.lock:%d: missing size band", headerLines+i+1)
		}
		out = append(out, r)
	}
	return out, nil
}

func headerDate(head string) (time.Time, error) {
	const marker = "# Generated "
	for _, line := range strings.Split(head, "\n") {
		rest, ok := strings.CutPrefix(line, marker)
		if !ok || !strings.HasSuffix(rest, ".") {
			continue
		}
		rest = strings.TrimSuffix(rest, ".")
		if !dateRE.MatchString(rest) {
			continue
		}
		when, err := time.Parse(time.DateOnly, rest)
		if err != nil {
			return time.Time{}, fmt.Errorf("repos.lock: bad generated date")
		}
		return when.UTC(), nil
	}
	return time.Time{}, fmt.Errorf("repos.lock: header is not the generated header")
}

// ParseTriage reads triage.tsv. The file must start with TriageHeader.
// Any other comment, a blank line, a carriage return, or a line over
// maxLineBytes is rejected.
func ParseTriage(data []byte) ([]Triage, error) {
	lines, err := bodyLines(data, TriageHeader, "triage.tsv")
	if err != nil {
		return nil, err
	}
	var out []Triage
	base := strings.Count(TriageHeader, "\n")
	for i, line := range lines {
		fields := strings.Split(line, "\t")
		if len(fields) != 6 {
			return nil, fmt.Errorf("triage.tsv:%d: %d columns, want 6", base+i+1, len(fields))
		}
		row := Triage{
			Fingerprint: fields[0],
			RuleID:      fields[1],
			Repo:        fields[2],
			Verdict:     fields[3],
			Reason:      fields[4],
			Date:        fields[5],
		}
		if err := checkTriage(row); err != nil {
			return nil, fmt.Errorf("triage.tsv:%d: %w", base+i+1, err)
		}
		out = append(out, row)
	}
	return out, nil
}

// bodyLines returns the data lines after header. The file must start
// with that header. A comment or a blank line after it is rejected.
func bodyLines(data []byte, header, file string) ([]string, error) {
	for i, line := range strings.Split(string(data), "\n") {
		if len(line) > maxLineBytes {
			return nil, fmt.Errorf("%s:%d: line is %d bytes, limit %d", file, i+1, len(line), maxLineBytes)
		}
	}
	if bytes.Contains(data, []byte{'\r'}) {
		return nil, fmt.Errorf("%s: carriage return", file)
	}
	if !bytes.HasPrefix(data, []byte(header)) {
		return nil, fmt.Errorf("%s: header is not the generated header", file)
	}
	rest := string(data[len(header):])
	if rest == "" {
		return nil, nil
	}
	lines := strings.Split(rest, "\n")
	if lines[len(lines)-1] == "" {
		lines = lines[:len(lines)-1]
	}
	base := strings.Count(header, "\n")
	for i, line := range lines {
		if line == "" || strings.HasPrefix(line, "#") {
			return nil, fmt.Errorf("%s:%d: comment or blank line outside the header", file, base+i+1)
		}
	}
	return lines, nil
}

// ParseRegistry reads rules/REGISTRY and returns the rule ids it lists.
// A comment or a blank line is skipped. Every other line starts with
// an id and a status, separated by whitespace.
func ParseRegistry(data []byte) (map[string]bool, error) {
	out := map[string]bool{}
	for i, line := range strings.Split(string(data), "\n") {
		line = strings.TrimRight(line, "\r")
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) < 2 || !ruleRE.MatchString(fields[0]) {
			return nil, fmt.Errorf("REGISTRY:%d: bad rule id", i+1)
		}
		out[fields[0]] = true
	}
	return out, nil
}

// Validate checks the lock and triage invariants: column shape is
// enforced by the parsers, then this checks SHA and verdict values,
// sorted unique repositories, unique repository and fingerprint pairs, that every triage
// rule id is in rules, and that every triage repository is in the lock.
// rules may be nil only when triage has no rows.
func Validate(repos []Repo, triage []Triage, rules map[string]bool) error {
	seen := map[string]bool{}
	var prev string
	for i, r := range repos {
		if err := checkRepo(r); err != nil {
			return fmt.Errorf("repo %d: %w", i+1, err)
		}
		if seen[r.Name] {
			return fmt.Errorf("duplicate repository %s", r.Name)
		}
		seen[r.Name] = true
		if i > 0 && strings.Compare(prev, r.Name) >= 0 {
			return fmt.Errorf("repositories are not sorted: %s then %s", prev, r.Name)
		}
		prev = r.Name
	}
	fps := map[[2]string]bool{}
	for i, row := range triage {
		if err := checkTriage(row); err != nil {
			return fmt.Errorf("triage %d: %w", i+1, err)
		}
		key := [2]string{row.Repo, row.Fingerprint}
		if fps[key] {
			return fmt.Errorf("duplicate fingerprint %s in repository %s", row.Fingerprint, row.Repo)
		}
		fps[key] = true
		if rules == nil || !rules[row.RuleID] {
			return fmt.Errorf("rule %s is not in the registry", row.RuleID)
		}
		if !seen[row.Repo] {
			return fmt.Errorf("triage repository %s is not in repos.lock", row.Repo)
		}
	}
	return nil
}

func checkRepo(r Repo) error {
	if !validRepoName(r.Name) {
		return fmt.Errorf("bad repository %q", r.Name)
	}
	if !shaRE.MatchString(r.SHA) {
		return fmt.Errorf("%s: bad SHA %q", r.Name, r.SHA)
	}
	if !knownLicense(r.License) {
		return fmt.Errorf("%s: unknown license %q", r.Name, r.License)
	}
	switch r.Band {
	case "", "small", "medium", "large":
	default:
		return fmt.Errorf("%s: bad size band %q", r.Name, r.Band)
	}
	if _, err := joinHarnesses(r.Harnesses); err != nil {
		return fmt.Errorf("%s: %w", r.Name, err)
	}
	if !validDate(r.Date) {
		return fmt.Errorf("%s: bad date %q", r.Name, r.Date)
	}
	return nil
}

func checkTriage(row Triage) error {
	if !fingerprintRE.MatchString(row.Fingerprint) {
		return fmt.Errorf("bad fingerprint %q", row.Fingerprint)
	}
	if !ruleRE.MatchString(row.RuleID) {
		return fmt.Errorf("bad rule id %q", row.RuleID)
	}
	if !validRepoName(row.Repo) {
		return fmt.Errorf("bad repository %q", row.Repo)
	}
	switch row.Verdict {
	case VerdictTP, VerdictFP, VerdictAccepted:
	default:
		return fmt.Errorf("bad verdict %q", row.Verdict)
	}
	if err := checkReason(row.Reason); err != nil {
		return err
	}
	if !validDate(row.Date) {
		return fmt.Errorf("bad date %q", row.Date)
	}
	return nil
}

func validRepoName(name string) bool {
	if !repoRE.MatchString(name) {
		return false
	}
	_, repo, _ := strings.Cut(name, "/")
	if repo == "." || repo == ".." {
		return false
	}
	return !randomName(name)
}

// randomName rejects a payload hidden in a repository name. Separators
// are removed so a hyphen cannot split one token into short pieces.
// Every 40-character window is then scored, because a low-entropy pad
// can hold the whole name under 4.5 while a window sits above it. A
// name shorter than 40 characters keeps the whole-string rule, which
// does not reject it. Hex entropy cannot exceed 4, so a run of 24 or
// more hex digits is rejected on its own. The highest window in the
// index is 4.43 and the longest hex run is 9.
func randomName(name string) bool {
	if hexRun(name) >= 24 {
		return true
	}
	s := strippedName(name)
	// Below 40 characters the whole-string rule cannot reject the name.
	if len(s) < reasonEntropyMin {
		return false
	}
	for i := 0; i+reasonEntropyMin <= len(s); i++ {
		if shannon(s[i:i+reasonEntropyMin]) > reasonEntropyMax {
			return true
		}
	}
	return false
}

func strippedName(name string) string {
	var b strings.Builder
	b.Grow(len(name))
	for i := 0; i < len(name); i++ {
		switch name[i] {
		case '/', '-', '_', '.':
		default:
			b.WriteByte(name[i])
		}
	}
	return b.String()
}

func hexRun(name string) int {
	best, cur := 0, 0
	for i := 0; i < len(name); i++ {
		if isHex(name[i]) {
			cur++
			if cur > best {
				best = cur
			}
			continue
		}
		cur = 0
	}
	return best
}

func isHex(c byte) bool {
	return (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') || (c >= 'A' && c <= 'F')
}

func validDate(s string) bool {
	if !dateRE.MatchString(s) {
		return false
	}
	_, err := time.Parse(time.DateOnly, s)
	return err == nil
}

func joinHarnesses(in []string) (string, error) {
	if len(in) == 0 {
		return "", fmt.Errorf("no harnesses")
	}
	seen := map[string]bool{}
	var list []string
	for _, h := range in {
		if !knownHarness(h) {
			return "", fmt.Errorf("unknown harness %q", h)
		}
		if seen[h] {
			return "", fmt.Errorf("duplicate harness %s", h)
		}
		seen[h] = true
		list = append(list, h)
	}
	slices.Sort(list)
	return strings.Join(list, ","), nil
}

func splitHarnesses(s string) []string {
	if s == "" {
		return nil
	}
	return strings.Split(s, ",")
}

func knownHarness(h string) bool {
	return slices.Contains(Harnesses, h)
}

// SizeBand reports small, medium, or large for a repository size in KB.
func SizeBand(kb int) string {
	switch {
	case kb < SizeSmallMaxKB:
		return "small"
	case kb < SizeMediumMaxKB:
		return "medium"
	default:
		return "large"
	}
}
