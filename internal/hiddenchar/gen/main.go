// Command gen writes pictographic.go, the Extended_Pictographic table of
// package hiddenchar, from Unicode's emoji-data.txt. It reads a local
// copy and never downloads one.
//
// The copy next to this file is Unicode 17.0 emoji-data.txt
// (https://www.unicode.org/Public/17.0.0/ucd/emoji/emoji-data.txt,
// sha256 2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b).
// To move to a newer Unicode version, replace that file, update
// unicodeVersion, and run go generate ./internal/hiddenchar.
package main

import (
	"bufio"
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"slices"
	"strconv"
	"strings"
)

const unicodeVersion = "17.0"

func main() {
	data := flag.String("data", "gen/emoji-data.txt", "emoji-data.txt to read")
	out := flag.String("out", "pictographic.go", "file to write")
	flag.Parse()
	if err := run(*data, *out); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run(data, out string) error {
	in, err := os.ReadFile(data)
	if err != nil {
		return err
	}
	src, err := Generate(bytes.NewReader(in))
	if err != nil {
		return fmt.Errorf("%s: %w", data, err)
	}
	return os.WriteFile(out, src, 0o644)
}

// Generate returns the formatted source of pictographic.go for the
// emoji-data.txt read from r. The file must declare unicodeVersion.
func Generate(r io.Reader) ([]byte, error) {
	ranges, version, err := parse(r)
	if err != nil {
		return nil, err
	}
	if version != unicodeVersion {
		return nil, fmt.Errorf("version %q, want %q", version, unicodeVersion)
	}
	if len(ranges) == 0 {
		return nil, errors.New("no Extended_Pictographic ranges")
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/hiddenchar/gen from Unicode %s emoji-data.txt; DO NOT EDIT.\n\n", unicodeVersion)
	b.WriteString("package hiddenchar\n\n")
	b.WriteString("// extendedPictographicRanges is Unicode Extended_Pictographic.\n")
	b.WriteString("var extendedPictographicRanges = []rune{\n")
	for _, rg := range ranges {
		fmt.Fprintf(&b, "\t0x%X, 0x%X,\n", rg[0], rg[1])
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// parse reads the Extended_Pictographic lines, sorted and with adjacent
// ranges merged, and the "# Version:" header.
func parse(r io.Reader) (ranges [][2]rune, version string, err error) {
	sc := bufio.NewScanner(r)
	for sc.Scan() {
		line := sc.Text()
		if v, ok := strings.CutPrefix(line, "# Version:"); ok && version == "" {
			version = strings.TrimSpace(v)
			continue
		}
		body, _, _ := strings.Cut(line, "#")
		codes, prop, ok := strings.Cut(body, ";")
		if !ok || strings.TrimSpace(prop) != "Extended_Pictographic" {
			continue
		}
		rg, err := parseRange(strings.TrimSpace(codes))
		if err != nil {
			return nil, "", err
		}
		ranges = append(ranges, rg)
	}
	if err := sc.Err(); err != nil {
		return nil, "", err
	}
	slices.SortFunc(ranges, func(a, b [2]rune) int { return int(a[0] - b[0]) })
	var merged [][2]rune
	for _, rg := range ranges {
		if n := len(merged); n > 0 && rg[0] <= merged[n-1][1]+1 {
			merged[n-1][1] = max(merged[n-1][1], rg[1])
			continue
		}
		merged = append(merged, rg)
	}
	return merged, version, nil
}

func parseRange(s string) ([2]rune, error) {
	lo, hi, ok := strings.Cut(s, "..")
	if !ok {
		hi = lo
	}
	a, err := strconv.ParseUint(lo, 16, 32)
	if err != nil {
		return [2]rune{}, fmt.Errorf("code point %q: %w", s, err)
	}
	b, err := strconv.ParseUint(hi, 16, 32)
	if err != nil || b < a || b > 0x10FFFF {
		return [2]rune{}, fmt.Errorf("code point range %q", s)
	}
	return [2]rune{rune(a), rune(b)}, nil
}
